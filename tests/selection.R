library(CDSeq2)
fails <- function(expr) stopifnot(inherits(try(force(expr),silent=TRUE),'try-error'))
x<-data.frame(gene=c('b','a','c','d','e','f'),cell_type=rep(c('type1','type2'),each=3),variation_score=c(5,5,NA,NA,NA,NA),status=c('ok','outside_training_range','undefined_feature',rep('unsupported_cell_type',3)),outside_training_range=c(FALSE,TRUE,NA,NA,NA,NA))
x$p<-c(.001,.01,.2,.3,.4,.5);x$q<-p.adjust(x$p,'BH')
y<-select_variation_profiles(x,.5)
stopifnot(identical(y$gene[y$retained],'a'),identical(y$p,x$p),identical(y$q,x$q),sum(y$retained)==1)
r<-summarize_variation_selection(y)
stopifnot(r$eligible[1]==2,r$retained[1]==1,r$fraction_total[1]==1/3,r$retained_outside_training_range[1]==1,r$unsupported[2]==3,is.na(r$fraction_eligible[2]))
stopifnot(!any(select_variation_profiles(x,0)$retained),sum(select_variation_profiles(x,1)$retained)==2)
rev<-select_variation_profiles(x[6:1,],.5);stopifnot(identical(rev$gene[rev$retained],'a'))
fails(select_variation_profiles(rbind(x,x[1,]),.5));fails(select_variation_profiles(x,-.1))
